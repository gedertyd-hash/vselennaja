export async function seedDemoContent(prisma: PrismaClient) {
  for (const material of DEMO_MATERIALS) {
    const course = await prisma.course.upsert({
      where: { slug: material.slug },
      update: {
        title: material.title,
        description: material.description,
        type: material.type,
        level: material.level,
        tag: material.tag,
        published: true,
      },
      create: {
        slug: material.slug,
        title: material.title,
        description: material.description,
        type: material.type,
        level: material.level,
        tag: material.tag,
        published: true,
      },
    });

    let moduleOrder = 0;
    for (const mod of material.modules) {
      const existingModule = await prisma.module.findFirst({
        where: { courseId: course.id, title: mod.title },
      });

      const moduleRecord =
        existingModule ??
        (await prisma.module.create({
          data: { courseId: course.id, title: mod.title, order: moduleOrder },
        }));

      let lessonOrder = 0;
      for (const lesson of mod.lessons) {
        await prisma.lesson.upsert({
          where: { moduleId_slug: { moduleId: moduleRecord.id, slug: lesson.slug } },
          update: {
            title: lesson.title,
            content: lesson.content,
            videoUrl: lesson.videoUrl,
            kind: lesson.kind,
            durationMinutes: lesson.durationMinutes,
            published: true,
          },
          create: {
            moduleId: moduleRecord.id,
            slug: lesson.slug,
            title: lesson.title,
            type: lesson.videoUrl ? "VIDEO" : "TEXT",
            content: lesson.content,
            videoUrl: lesson.videoUrl,
            kind: lesson.kind,
            durationMinutes: lesson.durationMinutes,
            published: true,
            order: lessonOrder,
          },
        });
        lessonOrder++;
      }
      moduleOrder++;
    }
  }

  return DEMO_MATERIALS.map((m) => m.slug);
}
