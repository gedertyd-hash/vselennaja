async function main() {
  for (const guide of guides) {
    const course = await prisma.course.upsert({
      where: { slug: guide.slug },
      update: {
        title: guide.title,
        description: guide.description,
        tag: guide.tag,
        level: guide.level,
      },
      create: {
        slug: guide.slug,
        title: guide.title,
        description: guide.description,
        type: "GUIDE",
        level: guide.level,
        tag: guide.tag,
        published: false,
        modules: {
          create: [
            {
              title: "Материал",
              order: 0,
              lessons: {
                create: [
                  {
                    slug: "content",
                    title: guide.title,
                    type: "TEXT",
                    content: guide.content,
                    published: false,
                    order: 0,
                  },
                ],
              },
            },
          ],
        },
      },
    });

    const existingLesson = await prisma.lesson.findFirst({
      where: { module: { courseId: course.id } },
    });
    if (existingLesson) {
      await prisma.lesson.update({
        where: { id: existingLesson.id },
        data: { title: guide.title, content: guide.content },
      });
    }

    console.log("upserted:", guide.slug);
  }
}

main()
  .then(async () => {
    await prisma.$disconnect();
  })
  .catch(async (e) => {
    console.error(e);
    await prisma.$disconnect();
    process.exit(1);
  });
