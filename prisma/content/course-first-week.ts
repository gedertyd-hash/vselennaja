async function main() {
  const course = await prisma.course.upsert({
    where: { slug: courseSlug },
    update: {
      title: courseTitle,
      description: courseDescription,
    },
    create: {
      slug: courseSlug,
      title: courseTitle,
      description: courseDescription,
      type: "COURSE",
      level: "BEGINNER",
      tag: "Основы",
      published: false,
    },
  });

  let moduleOrder = 0;
  for (const mod of modules) {
    const existingModule = await prisma.module.findFirst({
      where: { courseId: course.id, title: mod.title },
    });

    const moduleRecord =
      existingModule ??
      (await prisma.module.create({
        data: { courseId: course.id, title: mod.title, order: moduleOrder },
      }));

    let lessonOrder = 0;
    for (const lesson of mod.lessons) {
      await prisma.lesson.upsert({
        where: { moduleId_slug: { moduleId: moduleRecord.id, slug: lesson.slug } },
        update: { title: lesson.title, content: lesson.content },
        create: {
          moduleId: moduleRecord.id,
          slug: lesson.slug,
          title: lesson.title,
          type: "TEXT",
          content: lesson.content,
          published: false,
          order: lessonOrder,
        },
      });
      lessonOrder++;
    }
    moduleOrder++;
  }

  console.log("upserted course:", courseSlug);
}

main()
  .then(async () => {
    await prisma.$disconnect();
  })
  .catch(async (e) => {
    console.error(e);
    await prisma.$disconnect();
    process.exit(1);
  });
