// Список того, что может "выпасть" из капсулы. Отредактируйте под реальные
// призы/промокоды клиента. Можно сделать все варианты одинаковыми (просто
// единый промокод на скидку), если розыгрыш с разными призами не нужен.
export const PRIZES: string[] = [
  "Промокод на 10% на следующий заказ: WELCOME10",
  "Промокод на бесплатную доставку: FREESHIP",
  "Скидка 15% на вторую вещь: SECOND15",
];

export function pickPrize(): string {
  return PRIZES[Math.floor(Math.random() * PRIZES.length)];
}
